"""Vertical road profiles: ISO 8608 random roads and defined single obstacles.

ISO 8608 (2016) classifies roads by the one-sided displacement PSD

    G_d(n) = G_d(n0) (n / n0)^(-2),    n0 = 0.1 cycles/m

with the geometric-mean class values G_d(n0) = 16, 64, 256, ... 262144 * 1e-6 m^3
for classes A ... H. A profile is generated by harmonic superposition,

    z(x) = sum_i sqrt(2 G_d(n_i) dn) cos(2 pi n_i x + phi_i),   phi_i ~ U(0, 2 pi) (seeded)

on a uniform spatial-frequency grid, so its PSD equals G_d(n_i) at every grid
frequency (variance ``sum G_d dn``). At vehicle speed ``v`` the excitation is
``z(t) = z(x0 + v t)``, ``z'(t) = v dz/dx``.

Single obstacles: a half-sine bump of given height and length (smooth slope).
The profiles are synthetic test inputs, not measured roads.
"""

from __future__ import annotations

import math
from dataclasses import dataclass

import numpy as np

ISO8608_CLASSES = {c: 16e-6 * 4**i for i, c in enumerate("ABCDEFGH")}  # G_d(n0) [m^3]
N0 = 0.1  # [cycles/m]


class ISO8608Profile:
    """Random road profile of an ISO 8608 class."""

    def __init__(self, road_class: str = "B", seed: int = 0, n_min: float = 0.011, n_max: float = 2.83,
                 n_components: int = 2000):
        if road_class not in ISO8608_CLASSES:
            raise ValueError(f"road class must be one of {''.join(ISO8608_CLASSES)}")
        if not 0 < n_min < n_max or n_components < 2:
            raise ValueError("need 0 < n_min < n_max and at least two components")
        self.road_class = road_class
        self.Gd0 = ISO8608_CLASSES[road_class]
        self.n = np.linspace(n_min, n_max, n_components)
        self.dn = self.n[1] - self.n[0]
        self.amplitude = np.sqrt(2.0 * self.psd(self.n) * self.dn)
        self.phase = np.random.default_rng(seed).uniform(0.0, 2.0 * math.pi, n_components)

    def psd(self, n) -> np.ndarray:
        """Target one-sided displacement PSD G_d(n) [m^3]."""
        return self.Gd0 * (np.asarray(n, dtype=float) / N0) ** -2

    @property
    def variance(self) -> float:
        return float(np.sum(self.psd(self.n) * self.dn))

    def height(self, x) -> np.ndarray:
        x = np.atleast_1d(np.asarray(x, dtype=float))
        return np.cos(2 * math.pi * np.outer(x, self.n) + self.phase) @ self.amplitude

    def slope(self, x) -> np.ndarray:
        x = np.atleast_1d(np.asarray(x, dtype=float))
        return -np.sin(2 * math.pi * np.outer(x, self.n) + self.phase) @ (2 * math.pi * self.n * self.amplitude)


@dataclass(frozen=True)
class HalfSineBump:
    """Bump ``peak sin(pi (x - x0)/L)`` for ``x0 <= x <= x0 + L``, flat elsewhere."""

    x0: float = 5.0       # [m] start
    length: float = 0.5   # [m]
    peak: float = 0.05    # [m] height

    def height(self, x) -> np.ndarray:
        x = np.atleast_1d(np.asarray(x, dtype=float))
        inside = (x >= self.x0) & (x <= self.x0 + self.length)
        return np.where(inside, self.peak * np.sin(math.pi * (x - self.x0) / self.length), 0.0)

    def slope(self, x) -> np.ndarray:
        x = np.atleast_1d(np.asarray(x, dtype=float))
        inside = (x >= self.x0) & (x <= self.x0 + self.length)
        return np.where(inside, self.peak * math.pi / self.length * np.cos(math.pi * (x - self.x0) / self.length), 0.0)


__all__ = ("HalfSineBump", "ISO8608Profile", "ISO8608_CLASSES", "N0")
